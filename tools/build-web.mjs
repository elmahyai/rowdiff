#!/usr/bin/env node
// Bundles src/*.js into a single self-contained web/index.html.
// Everything runs client-side: no upload, no server, no analytics, no build toolchain.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

// Strip ESM syntax so the modules can be concatenated into one classic script.
function stripModuleSyntax(src) {
  return src
    .replace(/^import[\s\S]*?from\s+['"][^'"]+['"];?$/gm, '')
    .replace(/^export\s+(default\s+)?/gm, '');
}

const csv = stripModuleSyntax(read('src/csv.js'));
const diff = stripModuleSyntax(read('src/diff.js'));
const report = stripModuleSyntax(read('src/report.js'));
const detect = stripModuleSyntax(read('src/detect.js'));
const template = read('web/template.html');

const engine = `/* rowdiff engine - generated by tools/build-web.mjs. Do not edit index.html directly. */
(function () {
'use strict';
${csv}
${diff}
${report}
${detect}

window.Rowdiff = { parse, diff, render, detectKeys, hasDifferences, toText, toJson, toMarkdown, toHtml, parseNumber };
})();
`;

const out = template
  .replace('/*__ENGINE__*/', () => engine)
  .replace('__BUILD_DATE__', new Date().toISOString().slice(0, 10));

mkdirSync(join(root, 'web'), { recursive: true });
writeFileSync(join(root, 'web/index.html'), out);

const size = (Buffer.byteLength(out) / 1024).toFixed(1);
console.log(`web/index.html written (${size} kB, no external requests)`);

// Fail loudly if anything secret or Node-only leaks into the shipped bundle.
const secretPatterns = [/BEGIN [A-Z ]*PRIVATE KEY/, /ROWDIFF\.eyJ/];
for (const re of secretPatterns) {
  if (re.test(out)) {
    console.error(`ERROR: bundled output matches secret pattern ${re}`);
    process.exitCode = 1;
  }
}

// Fail loudly if the bundle accidentally depends on Node APIs.
const forbidden = ['require(', 'process.env', 'node:'];
for (const token of forbidden) {
  if (out.includes(token)) {
    console.error(`ERROR: bundled output contains Node-only API "${token}"`);
    process.exitCode = 1;
  }
}
